def generate():
    out_path = Path(__file__).parent / "datasets" / "naca0012_multi_re_polars.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for re, pts in sorted(RAW_DATA.items()):
        for alpha, cl, cd in pts:
            rows.append((alpha, re, cl, cd))

    rows.sort(key=lambda r: (r[1], r[0]))

    with open(out_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["angle_of_attack", "reynolds_number", "cl", "cd"])
        for alpha, re, cl, cd in rows:
            writer.writerow([alpha, re, cl, cd])

    print(f"[Dataset] Generated {len(rows)} rows -> {out_path}")
    return str(out_path)


if __name__ == "__main__":
    generate()
